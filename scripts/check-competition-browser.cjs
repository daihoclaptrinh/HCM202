    await guest.keyboard.down('KeyW'); await guest.waitForTimeout(250); await guest.keyboard.up('KeyW')
    assert.equal(await guest.evaluate(() => window.testExperience.camera.position.z), before, 'Cannot walk away during question')
    await guest.screenshot({ path: path.join(os.tmpdir(), 'hcm202-locked-question.png') })
