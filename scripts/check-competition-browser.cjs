    await guest.locator('#result-screen').waitFor({ state: 'visible' })
    await peer.locator('#result-screen').waitFor({ state: 'visible' })
    for (const page of [guest, peer]) assert.equal(await page.evaluate(key => localStorage.getItem(key), tokenKey), null, 'Host end removes resume token')
