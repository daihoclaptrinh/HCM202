const { chromium } = require('playwright-core')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH || path.join(process.env.LOCALAPPDATA, 'ms-playwright/chromium-1234/chrome-win64/chrome.exe') })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const sockets = []; page.on('websocket', socket => { if (new URL(socket.url()).pathname === '/live') sockets.push(socket.url()) })
    await page.goto(process.env.GAME_URL || 'http://127.0.0.1:5173/')
    await page.locator('#visit-free-button').waitFor({ state: 'visible', timeout: 60000 })
    assert.equal(await page.locator('#player-name').isVisible(), false)
    await page.screenshot({ path: 'review-visitor-start.png' })
    await page.click('#visit-free-button')
    await page.locator('#lesson-gate').waitFor({ state: 'visible' })
    assert.equal(await page.evaluate(() => !!document.fullscreenElement), false)
    assert.equal(await page.locator('#stage-quiz').isVisible(), false)
    assert.equal(await page.locator('#scoreboard').isVisible(), false)
    await page.keyboard.down('KeyW'); await page.waitForTimeout(6500); await page.keyboard.up('KeyW')
    await page.waitForFunction(() => document.querySelector('#chapter').textContent.includes('01 / 05'))
    assert.equal(await page.locator('#stage-quiz').isVisible(), false)
    // The same focus events that lose a competitive round leave a visit usable.
    await page.evaluate(() => { window.dispatchEvent(new Event('blur')); document.dispatchEvent(new Event('fullscreenchange')); Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); Object.defineProperty(document, 'hidden', { configurable: true, get: () => false }) })
    assert.equal(await page.locator('#result-screen').isVisible(), false)
    await page.click('#journal-button')
    assert.equal(await page.locator('#journal').innerText().then(text => text.includes('trắc nghiệm')), false)
    await page.locator('#journal .close').click()
    await page.click('#home-button'); await page.click('#visit-guided-button')
    await page.click('#guided-next'); await page.click('#guided-next')
    await page.locator('#lesson-listen').waitFor({ state: 'visible' })
    assert.equal(await page.locator('#guided-next').isDisabled(), false)
    await page.click('#guided-next'); await page.click('#guided-next'); await page.click('#guided-next')
    await page.waitForFunction(() => document.querySelector('#lesson-title').textContent.includes('1911'))
    assert.equal(await page.locator('#stage-quiz').isVisible(), false)
    await page.click('#lesson-listen')
    await page.waitForFunction(() => document.querySelector('#lesson-listen').textContent.includes('TẠM DỪNG'))
    await page.click('#home-button')
    await page.click('#competitive-tab'); assert.equal(await page.locator('#player-name').isVisible(), true)
    assert.deepEqual(sockets, []); assert.deepEqual(errors, [])
    console.log('PASS: independent visitor mode, free movement, optional audio, guided skip, focus events and competitive entry')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
